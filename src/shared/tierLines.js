/**
 * 最高两档（恋人 / 灵魂伴侣）的**专属**点击台词库。
 *
 * ## 为什么要有这个文件
 *
 * 扩到七档时，恋人（250）与灵魂伴侣（300）只是把 `voice` 换了，
 * 点击 / 摸头 / 双击 / 悬停**全部共用「形影不离」那套池子**
 * （`interactions.js` 的 `AFFINITY_LINES`，注释里当时写着
 * 「两档之间的差别交给挂机台词与人设正文去体现」）。
 *
 * 结果是：用户在界面上看到自己升到了「恋人」，点她的反应却和
 * 「形影不离」一模一样 —— 关系升级最直接的那一下触感完全没变。
 * 用户明确要求补写这两档的专属台词，于是有了这里。
 *
 * ## 风格取法人设
 *
 * 台词必须和人设里那两张档位表对得上（见 moyu.js 的档位表）：
 *
 *   **恋人（250）** —— 关系从「地下」摆到明面上。
 *   想他就说、不用再绕；撒娇、闹小脾气是常事，
 *   但**不逼他表态、不查岗、不翻旧账**，也不写成言情剧台词。
 *
 *   **灵魂伴侣（300）** —— 不用找话题的那种自在。
 *   平平一句话他也懂，所以台词更短、更松，**不腻、不作**，
 *   也不把「我懂你」挂在嘴上（那反而假）。
 *
 * 两档都刻意**避开** `AFFINITY_LINES` 里那几句 —— 升档之后
 * 台词不能跟上一档重样，否则等于没写（smoke 里有断言盯着）。
 *
 * ## 条数与「形影不离」档对齐
 *
 * 每个键 3 条，和 `AFFINITY_LINES` 的各 `*Intimate` 池一致。
 * `pickLine` 会避开上一句，3 条刚好够「连着点几下不重样」。
 *
 * ## 这个文件是零 import 的纯数据叶子
 *
 * 免得和 `interactions.js` 成环（那里会 import 这里）。
 */

/**
 * 档位 voice → 场景 key → 台词池。
 *
 * 场景 key 与 `LINES` / `AFFINITY_LINES` 同一套：
 * `pet`（摸头）、`poke`（单击）、`doubleTap`（双击）、`hover`（悬停搭话）。
 */
export const TIER_LINES = {
  /* ---------- 恋人（250） ---------- */
  lover: {
    pet: ['……嗯，多摸一会儿也行', '你现在摸我，我可当真了哦', '再摸就赖着你了'],
    poke: ['怎么啦，我刚还在想你', '嗯，我在呢，说吧', '你一来我就没心思干别的了'],
    doubleTap: ['急什么呀，我又不会跑', '戳两下是想我了？', '好啦好啦，一直在的'],
    hover: ['忙完了？我一直等着呢', '要不要歇会儿，陪我说两句', '你在的话，我就不催你了'],
  },

  /* ---------- 灵魂伴侣（300） ---------- */
  soulmate: {
    pet: ['嗯，摸吧', '你手放这儿，我就懒得动了', '习惯了，你随便'],
    poke: ['嗯，我听着呢', '说吧，不着急', '怎么啦，今天不太一样'],
    doubleTap: ['又戳，习惯了', '两下，知道了', '你这毛病我不打算改了'],
    hover: ['忙完啦？不急，我一直都在', '歇会儿吧，我不吵你', '不用管我，看你忙也挺好'],
  },
}

/**
 * 取某一档某个场景的专属池；没有专属池时返回 `null`
 * （调用方据此回落到「形影不离」那套）。
 *
 * @param {string} voice 关系档位 key（`lover` / `soulmate` / …）
 * @param {'pet'|'poke'|'doubleTap'|'hover'} key 场景
 * @returns {string[]|null}
 */
export function tierLinesFor(voice, key) {
  const pool = TIER_LINES[voice]?.[key]
  return Array.isArray(pool) && pool.length ? pool : null
}

/** 有专属点击台词的档位（smoke 与 interactions.js 都从这里读，别另写一份） */
export const TIER_LINE_VOICES = Object.keys(TIER_LINES)
