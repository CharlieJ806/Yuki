/**
 * 「点她」的台词库 —— 手机端立绘页专用。
 *
 * ## 为什么单独一个文件、为什么这么多条
 *
 * 用户要求「写死台词，但内容丰富到 100 条」。
 *
 * 写死（而不是每次调模型）的理由：**点击是高频动作** ——
 * 每点一下都等接口，手感会烂掉；而且点击时的反应要**立刻**出现，
 * 等 1~2 秒才「诶嘿」就完全没有互动的感觉了。
 *
 * 100 条的理由：台词少了会立刻被察觉在重复。
 * 实测 6 条的量，连点七八次就开始眼熟；100 条配上不重复的抽取
 * （见 `pickTapLine` 的轮转机制），能撑很久不出戏。
 *
 * ## 分组
 *
 * 按**亲密度**分三档，越熟越放得开：
 *   - `冷`（points < 40）：客气、有点距离
 *   - `熟`（40 ~ 119）：自然、开始开玩笑
 *   - `热`（>= 120）：黏人、撒娇、带点暧昧
 *
 * 这样「关系进展」在点击时就能被感觉到，而不只是看进度条。
 * 每档 30 条左右，另有一批 `通用` 的不分层台词。
 *
 * ## 与 `LINES` 的关系
 *
 * `shared/interactions.js` 的 `LINES` 是**桌面端桌宠**用的（pet/poke/
 * doubleTap/dragged/sedentary 等，每类 3~7 句）。那份是给鼠标交互的，
 * 量小、偏「桌面挂件」的语气。
 *
 * 这份是给手机端立绘页的独立扩充，**不改动 `LINES`** ——
 * 桌面端的行为不该因为手机端要更多台词而变。
 */
import { AFFINITY_LEVELS } from './interactions.js'

/**
 * 亲密度分档的边界。
 *
 * 取值刻意与 `AFFINITY_LEVELS` 的等级名对齐但不完全相同：
 *   - 40  = 「好朋友」的门槛
 *   - 120 = 「默契搭档」的门槛
 * 点击台词只分三档就够了 —— 五档的话每档只有 20 条，轮转太快。
 */
export const TAP_TIERS = {
  COLD: 40,
  WARM: 120,
}

/** 亲密度 → 档次 key */
export function tapTier(points) {
  const p = Number(points) || 0
  if (p >= TAP_TIERS.WARM) return 'hot'
  if (p >= TAP_TIERS.COLD) return 'warm'
  return 'cold'
}

