/**
 * 从一组台词里取一条，**尽量不重复**。
 *
 * ## 为什么不能纯随机
 *
 * `Math.random()` 取 100 条也会连撞 —— 生日悖论：取 12 次就有
 * 一半概率撞。实测连点十下看到同一句台词，立刻就觉得「这是个死程序」。
 *
 * ## 做法：洗牌袋（shuffle bag）
 *
 * 把整组打乱后**依次取完**，取完了再重新洗一袋。
 * 保证「一轮内绝不重复」，又保留了每轮的随机顺序。
 * 这是游戏里做随机播放/随机刷怪的成熟做法。
 *
 * 袋子的状态存在模块级（按「组 + 档次」分开存），不进存储 ——
 * 它只影响手感，刷新页面重置无妨。
 */
const bags = new Map()

function shuffle(arr) {
  const a = [...arr]
  for (let i = a.length - 1; i > 0; i--) {
    const j = Math.floor(Math.random() * (i + 1))
    ;[a[i], a[j]] = [a[j], a[i]]
  }
  return a
}

/**
 * @param {string[]} pool 候选台词
 * @param {string}   bagKey 袋子标识（不同组/档次各用各的）
 * @returns {string} 一条台词
 */
export function pickFromBag(pool, bagKey) {
  if (!Array.isArray(pool) || !pool.length) return ''
  let bag = bags.get(bagKey)

  /*
   * 什么时候重洗：袋子空了，或者**池子内容变了**。
   *
   * 「池子变了」的判据不能写成 `bag.length !== pool.length` ——
   * 取过一张后袋子自然比池子短，那样会**每次都重洗**，
   * 洗牌袋等于失效（实测：取 23 次只覆盖 14 张、重复 9 次，
   * 跟纯随机没区别）。正确判据是「袋子里还有没有池子外的元素」。
   *
   * 池子会变是因为调用方按昼夜切换候选集（见 mobile/app.js 的
   * `pickPetPose`）—— 不重洗的话，新池的元素要等旧袋取完才出现。
   */
  const stale = bag && bag.some((p) => !pool.includes(p))
  if (!bag || !bag.length || stale) {
    bag = shuffle(pool)
    bags.set(bagKey, bag)
  }

  const line = bag.pop()
  /*
   * 袋子空了就把键清掉，下一轮重新洗。
   * 注意是**把原来的池子重洗**而不是继续用被掏空的数组 ——
   * 否则第二轮只剩一条，取完就没有了。
   */
  if (!bag.length) bags.set(bagKey, null)
  return line
}

/* 调试用：看袋子状态（避免测试之间互相影响） */
export function resetBags() {
  bags.clear()
}

/**
 * 点击类型 → 该用哪一组台词。
 *
 * @param {string} kind 'tap' | 'double' | 'hold' | 'return'
 * @param {number} points 当前亲密度
 */
export function linesForTap(kind, points) {
  const tier = tapTier(points)
  if (kind === 'double') return DOUBLE_TAP_LINES[tier] ?? []
  if (kind === 'hold') return HOLD_LINES[tier] ?? []
  if (kind === 'return') return RETURN_LINES[tier] ?? []
  return TAP_LINES[tier] ?? []
}

/**
 * 取一条点击台词。
 *
 * @param {object} args
 * @param {string} args.kind   'tap' | 'double' | 'hold' | 'return'
 * @param {number} args.points 亲密度
 * @returns {string}
 */
export function pickTapLine({ kind = 'tap', points = 0 }) {
  const tier = tapTier(points)
  const pool = linesForTap(kind, points)
  return pickFromBag(pool, `${kind}:${tier}`)
}

/**
 * 全部台词的条数 —— 供测试断言「确实有 100 条以上」。
 *
 * 只数**单击**那三档：用户说的「100 条」指的是「点她的反应」，
 * 双击/长按是附加的，不该算进去凑数。
 * 当前 37 + 40 + 40 = 117 条。
 */
export function tapLineCount() {
  return Object.values(TAP_LINES).reduce((n, arr) => n + arr.length, 0)
}
